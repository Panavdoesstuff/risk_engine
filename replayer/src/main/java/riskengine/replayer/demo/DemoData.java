package riskengine.replayer.demo;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import riskengine.margin.MarginConfig;
import riskengine.margin.UnderlyingParams;
import riskengine.pricing.BlackScholes;
import riskengine.pricing.TimeToExpiry;
import riskengine.ref.Instrument;
import riskengine.ref.InstrumentCsv;
import riskengine.ref.InstrumentType;

/**
 * SYNTHETIC inputs for running the whole pipeline before the real market data is in place. Every price
 * here is made up by a formula. Nothing produced from these files may be quoted as a result about
 * 4 June 2024; the real replay (M7) uses NSE data.
 *
 * <p>What it writes:
 * <ul>
 *   <li>{@code processed/instruments-2024-06-03.csv}: two futures and two option expiries, strikes
 *       21,500 to 25,000, "settled" at the engine's own Black-Scholes price for spot 23,260 and VIX 20.9.</li>
 *   <li>{@code raw/SYNTHETIC-NIFTY-1m.csv}: minute bars for 3 June (flat) and 4 June (a fall of about 8%
 *       by early afternoon and a partial recovery).</li>
 *   <li>{@code raw/SYNTHETIC-INDIAVIX.csv}: daily values.</li>
 * </ul>
 * The raw files go through the normal {@code bars} command, so the same loaders run as for real data.
 * Output is deterministic: no random numbers, no clock.
 */
public final class DemoData {
    public static final String VIX_CLOSE_3_JUNE = "20.90";
    private static final double SPOT_3_JUNE = 23_260;

    private DemoData() {}

    /** @return a short description of what was written */
    public static String write(Path dir) {
        MarginConfig cfg = MarginConfig.defaults();
        UnderlyingParams p = cfg.params("NIFTY");
        LocalDate asOf = LocalDate.of(2024, 6, 3);
        long valuation = TimeToExpiry.expiryMillis(asOf);
        double vol = Double.parseDouble(VIX_CLOSE_3_JUNE) * p.volScale();

        List<Instrument> instruments = new ArrayList<>();
        for (LocalDate expiry : List.of(LocalDate.of(2024, 6, 27), LocalDate.of(2024, 7, 25))) {
            BigDecimal settle = money(BlackScholes.futures(SPOT_3_JUNE, TimeToExpiry.years(expiry, valuation), cfg.riskFreeRate(), p.dividendYield()));
            instruments.add(Instrument.of("NIFTY", InstrumentType.FUT, expiry, null, 25, settle, settle, 500_000));
        }
        for (LocalDate expiry : List.of(LocalDate.of(2024, 6, 6), LocalDate.of(2024, 6, 13))) {
            double t = TimeToExpiry.years(expiry, valuation);
            for (int k = 21_500; k <= 25_000; k += 100) {
                for (InstrumentType type : List.of(InstrumentType.CE, InstrumentType.PE)) {
                    BigDecimal settle = money(Math.max(0.05, BlackScholes.price(type, SPOT_3_JUNE, k, t, vol, cfg.riskFreeRate(), p.dividendYield())));
                    instruments.add(Instrument.of("NIFTY", type, expiry, BigDecimal.valueOf(k), 25, settle, settle, 100_000));
                }
            }
        }

        StringBuilder bars = new StringBuilder("DATETIME,OPEN,HIGH,LOW,CLOSE\n");
        double previous = SPOT_3_JUNE;
        for (LocalDate day : List.of(asOf, LocalDate.of(2024, 6, 4))) {
            for (int m = 0; m < 375; m++) {
                double close = day.equals(asOf) ? SPOT_3_JUNE + 12 * Math.sin(m / 9.0) : crashDay(m);
                double open = previous;
                bars.append(day).append('T').append(LocalTime.of(9, 15).plusMinutes(m)).append(":00,")
                        .append(fmt(open)).append(',').append(fmt(Math.max(open, close) + 1.5)).append(',')
                        .append(fmt(Math.min(open, close) - 1.5)).append(',').append(fmt(close)).append('\n');
                previous = close;
            }
        }
        String vix = "DATE,OPEN,HIGH,LOW,CLOSE\n"
                + "2024-05-31,24.20,24.90,23.80,24.60\n"
                + "2024-06-03,21.80,22.40,20.20," + VIX_CLOSE_3_JUNE + "\n"
                + "2024-06-04,22.10,31.70,21.90,26.75\n";
        try {
            Path processed = Files.createDirectories(dir.resolve("processed")), raw = Files.createDirectories(dir.resolve("raw"));
            InstrumentCsv.write(processed.resolve("instruments-2024-06-03.csv"), instruments);
            Files.writeString(raw.resolve("SYNTHETIC-NIFTY-1m.csv"), bars, StandardCharsets.UTF_8);
            Files.writeString(raw.resolve("SYNTHETIC-INDIAVIX.csv"), vix, StandardCharsets.UTF_8);
            Files.writeString(dir.resolve("README-SYNTHETIC.txt"),
                    "Everything under this directory was generated by `replayer demo`. The prices are made up.\n"
                            + "It exists to run the pipeline end to end; it says nothing about the real 4 June 2024.\n", StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return "SYNTHETIC demo data in " + dir + ": " + instruments.size() + " instruments, 750 minute bars (3-4 June), daily VIX; 3 June VIX close "
                + VIX_CLOSE_3_JUNE + "\n";
    }

    /** A made-up crash: opens lower, slides about 8% over three hours, recovers a third of it, with small waves. */
    static double crashDay(int minute) {
        double open = 23_180;
        double trend = minute <= 190 ? -1_850.0 * minute / 190 : -1_850 + 600.0 * (minute - 190) / 184;
        return open + trend + 25 * Math.sin(minute / 7.0);
    }

    private static BigDecimal money(double v) {
        return new BigDecimal(v).setScale(2, RoundingMode.HALF_UP);
    }

    private static String fmt(double v) {
        return String.format(Locale.ROOT, "%.2f", v);
    }
}
